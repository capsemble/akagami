// ---------------------------------------------------------------------------
// Staging: how an act is played in the world rather than in a panel.
//
// A mechanic's params are numbers. A stage says where each number comes from —
// a place you walk to, a needle you push, a drag you aim — and how the run that
// follows is acted out in the scene. Acts without a stage fall back to the
// slider panel, which is still the right answer for a quantity with nowhere to
// stand.
// ---------------------------------------------------------------------------

/**
 * A straight run across the world plane, and what the simulation calls its two
 * ends. This is what lets a scalar in metres or km/h be somewhere you can
 * stand: world pixels at one end, sim units at the other.
 */
export interface WorldPath {
  from: Point;
  to: Point;
  /** The sim-unit value at `from`, and at `to`. */
  fromValue: number;
  toValue: number;
  /** Shown beside the value while the player chooses, e.g. 'm'. */
  unit?: string;
}

/** Where a param's value comes from, when it comes from the world. */
export type ParamBinding =
  /** Walk the path, press E to plant a marker. The value is where you planted it. */
  | { kind: 'marker'; param: string; path: WorldPath; prompt?: string }
  /**
   * A needle on a dial you stand at: left/right nudge it, E commits. The band
   * is painted on the face, so leaving it is something you watch happen.
   */
  | {
      kind: 'needle';
      param: string;
      at: Point;
      band?: { from: number; to: number; label?: string };
      unit?: string;
      prompt?: string;
    }
  /**
   * A param the player holds down *during* the run rather than setting before
   * it. The act becomes live: the physics is stepped frame by frame with
   * whatever is being held, so when you act is the answer, not what you typed.
   */
  | {
      kind: 'control';
      param: string;
      /** The value while the key is down. The param's min applies while it is up. */
      held: number;
      label?: string;
      prompt?: string;
    }
  /** Drag from an anchor. One gesture, two params: the drag vector itself. */
  | {
      kind: 'aim';
      at: Point;
      paramX: string;
      paramY: string;
      /** Screen pixels of drag that reach each param's max. */
      maxDrag?: number;
      prompt?: string;
    };

/**
 * How a finished run is acted out. Expressions are read per sample against the
 * simulation scope, exactly as SimVisual's are, so the thing moving in the
 * scene and the curve in the panel are driven by the same numbers.
 */
export interface Playback {
  actor: 'train' | 'satchel';
  /**
   * Someone else moving on the same path, on their own clock. A rival turns a
   * target into a race: the concept stops being the subject and becomes the
   * choice you make under pressure.
   */
  rival?: { along: string; label: string };
  /** The line the actor travels along. */
  path: WorldPath;
  /** Per-sample distance along `path`, in that path's units. */
  along: string;
  /** Per-sample height above the path, same units, for a flight. */
  lift?: string;
  /** World pixels per unit of `lift`. Defaults to the path's own scale. */
  liftScale?: number;
  /** Seconds the replay should take, regardless of simulated time. Ignored on a
   *  live act, which takes exactly as long as it takes. */
  seconds?: number;
}

export interface ActStage {
  bindings: ParamBinding[];
  /** Absent means the verdict is immediate: nothing travels. */
  playback?: Playback;
  /** E on one of these shows what it says instead of playing the act. */
  readables?: Record<string, { speaker: string; lines: string[] }>;
  /**
   * One number worth saying out loud when a run ends. "Stopped at 133 m" is
   * feedback you can act on; "Not yet" is a shrug.
   */
  readout?: { output: string; label: string; unit?: string };
}
