export type WorldStatus =
  'reading' | 'designing' | 'validating' | 'painting' | 'mapping' | 'ready' | 'failed';

export interface Point {
  x: number;
  y: number;
}

export interface Rect {
  x: number;
  y: number;
  w: number;
  h: number;
  /** Extrusion height for isometric rendering. Ignored in top-down scenes. */
  height?: number;
}

export interface World {
  id: string;
  title: string;
  logline: string;
  artStyle: string;
  cast: Character[];
  acts: Act[];
  status: WorldStatus;
  /**
   * Set when this world was NOT built from the chapter that was uploaded —
   * a prepared world standing in because the models were unreachable, or
   * because the client is in mock mode. Silence here was the worst bug in the
   * upload path: a chapter on computer vision would quietly return a detective
   * story about trains and nothing on screen said why.
   */
  substituted?: string;
  /** Who you are actually up against. Named in the outline, shown at the end. */
  villain?: string;
  /** The turn the last act earns. Generated by the story agent and, until now,
   *  thrown away: the runtime contract had nowhere to put it. */
  twist?: string;
  /** Cached three.js diorama shown behind the world-forming screen. */
  dioramaUrl?: string;
}

export interface Character {
  id: string;
  name: string;
  persona: string;
  portraits: { neutral: string; pleased: string; worried: string };
  sprite: string;
}

export type Verb =
  'drive' | 'aim_launch' | 'plant_marker' | 'interrogate' | 'deduction' | 'intercept' | 'tune';

export interface Prediction {
  question: string;
  options: string[];
  correctIndex: number;
}

export interface Act {
  id: string;
  conceptId: string;
  title: string;
  goal: string;
  verbs: Verb[];
  sceneId: string;
  prediction?: Prediction;
  explainAfter: string;
  /** How the act is actually played. Absent on acts that are dialogue only. */
  mechanic?: Mechanic;
  /** How the mechanic is staged in the scene. Absent falls back to sliders. */
  stage?: ActStage;
  /** Played on entering the act. At most 6 lines, each at most 25 words. */
  dialogue?: DialogueLine[];
  /**
   * What the cast says the instant it lands or doesn't. The moment you win is
   * the worst possible time to be taught at — it wants a reaction. The physics
   * lives in `explainAfter`, which the player opens if they want it.
   */
  beat?: { won: string; lost: string; speaker?: string };
}

/**
 * A thing in the room you can walk up to and use.
 *
 * `label` and `look` are the design pass's own words for it, carried through so
 * the renderer can draw a lever as a lever. Optional because the hand-written
 * fixture scenes predate them and a bare id still names most props well enough.
 */
export interface Interactable extends Rect {
  id: string;
  /** What the cast calls it, shown on the plate over it. */
  label?: string;
  /** What it is made of or looks like. Picks the palette. */
  look?: string;
}

export interface Scene {
  id: string;
  /**
   * Painted backdrop. Optional: a room the mapper lays out has no painting
   * until an art pass gives it one, and the scene draws its own floor instead.
   */
  imageUrl?: string;
  /** Size of the flat world plane the colliders live on. */
  width: number;
  height: number;
  /** How the plane is drawn. Absent means 'topdown', as before. */
  projection?: 'topdown' | 'isometric';
  /** Pixel size of the projected background. Absent means width x height. */
  view?: { width: number; height: number };
  blocked: Rect[];
  interactables: Interactable[];
  exits: Rect[];
  spawn: Point;
  npcSpots: Record<string, Point>;
}

